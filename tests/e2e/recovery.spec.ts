import { expect, test } from "./fixtures";
import { emailLink } from "./emailHelpers";

test("verify email and recover a forgotten password through emailed links", async ({ page, request }) => {
  await page.goto("/register");
  await page.getByLabel("First Name").fill("Recovery");
  await page.getByLabel("Last Name").fill("Browser");
  await page.getByLabel("Username").fill("recovery_browser");
  await page.getByLabel("Email", { exact: true }).fill("recovery-browser@example.com");
  await page.getByLabel("Password", { exact: true }).fill("original-long-password");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("link", { name: "Manage verification" })).toBeVisible();
  await page.goto(await emailLink(request, "recovery-browser@example.com", "Verify your TaskFlow email"));
  await expect(page.getByRole("button", { name: "Verify email", exact: true })).toBeVisible();
  expect(new URL(page.url()).hash).toBe("");
  await page.getByRole("button", { name: "Verify email", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Email verified");
  await page.getByRole("link", { name: "Account settings", exact: true }).click();
  await expect(page.getByText("Your email is verified.")).toBeVisible();
  await page.getByRole("button", { name: "Logout", exact: true }).click();
  await page.getByRole("link", { name: "Forgot password?" }).click();
  await page.getByLabel("Email", { exact: true }).fill("recovery-browser@example.com");
  await page.getByRole("button", { name: "Send reset link" }).click();
  await expect(page.getByRole("status")).toContainText("If a password account exists");
  const link = await emailLink(request, "recovery-browser@example.com", "Reset your TaskFlow password");
  await page.goto(link);
  await page.getByLabel("New password", { exact: true }).fill("replacement-long-password");
  await page.getByLabel("Confirm new password").fill("replacement-long-password");
  await page.getByRole("button", { name: "Reset password", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Password reset");
  await page.getByRole("link", { name: "Back to sign in" }).click();
  await page.getByLabel("Email", { exact: true }).fill("recovery-browser@example.com");
  await page.getByLabel("Password", { exact: true }).fill("replacement-long-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "My Projects" })).toBeVisible();
  await page.goto(link);
  await page.getByLabel("New password", { exact: true }).fill("another-long-password");
  await page.getByLabel("Confirm new password").fill("another-long-password");
  await page.getByRole("button", { name: "Reset password", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("invalid or expired");
});
